// SSE2 4x4 transpose tiles for clockwise rotation.
TEXT ·rotateXRGB90AMD64(SB), NOSPLIT, $0-96
	MOVQ dst_base+0(FP), AX
	MOVQ dstStride+24(FP), BX
	MOVQ src_base+32(FP), CX
	MOVQ srcStride+56(FP), R8
	MOVQ width+64(FP), R9
	MOVQ height+72(FP), R10
	MOVQ startY+80(FP), R11
	MOVQ endY+88(FP), R12
yloop90:
	CMPQ R11, R12
	JGE done90
	XORQ R13, R13
xloop90:
	CMPQ R13, R9
	JGE nexty90
	MOVQ R10, R14
	SUBQ R11, R14
	SUBQ $4, R14
	SHLQ $2, R14
	MOVQ R13, SI
	IMULQ R8, SI
	ADDQ CX, SI
	ADDQ R14, SI
	MOVOU (SI), X0
	PSHUFD $0x1b, X0, X0
	ADDQ R8, SI
	MOVOU (SI), X1
	PSHUFD $0x1b, X1, X1
	ADDQ R8, SI
	MOVOU (SI), X2
	PSHUFD $0x1b, X2, X2
	ADDQ R8, SI
	MOVOU (SI), X3
	PSHUFD $0x1b, X3, X3
	MOVOU X0, X4
	PUNPCKLLQ X1, X4
	MOVOU X0, X5
	PUNPCKHLQ X1, X5
	MOVOU X2, X6
	PUNPCKLLQ X3, X6
	MOVOU X2, X7
	PUNPCKHLQ X3, X7
	MOVOU X4, X8
	PUNPCKLQDQ X6, X8
	MOVOU X4, X9
	PUNPCKHQDQ X6, X9
	MOVOU X5, X10
	PUNPCKLQDQ X7, X10
	MOVOU X5, X11
	PUNPCKHQDQ X7, X11
	MOVQ R11, R14
	IMULQ BX, R14
	ADDQ AX, R14
	MOVQ R13, DI
	SHLQ $2, DI
	ADDQ DI, R14
	MOVOU X8, (R14)
	ADDQ BX, R14
	MOVOU X9, (R14)
	ADDQ BX, R14
	MOVOU X10, (R14)
	ADDQ BX, R14
	MOVOU X11, (R14)
	ADDQ $4, R13
	JMP xloop90
nexty90:
	ADDQ $4, R11
	JMP yloop90
done90:
	RET

